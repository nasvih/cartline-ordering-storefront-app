/** `arCount(3, 'order')` → "3 طلبات" · `arCount(1, 'order')` → "طلب واحد" */
export function arCount(n, noun) {
  const f = AR_NOUNS[noun] || AR_NOUNS.item;
  /* `num()` hands over a grouped string — "1,240" — so strip the grouping. */
  const v = Number(String(n).replace(/,/g, '')) || 0;
  if (v === 0) return f.zero;
  if (v === 1) return f.one;
  if (v === 2) return f.two;
  if (v >= 3 && v <= 10) return `${v} ${f.few}`;
  return `${v} ${f.many}`;
}

/** The plural word on its own, for a phrase that already carries its number. */
export function arWord(n, noun) {
  const f = AR_NOUNS[noun] || AR_NOUNS.item;
  const v = Number(String(n).replace(/,/g, '')) || 0;
  if (v === 1) return f.one;
  if (v === 2) return f.two;
  if (v >= 3 && v <= 10) return f.few;
  return f.many;
}

/** A Latin run inside Arabic prose. Unicode isolates, so it works in text
    nodes as well as in markup. Nothing at all in English. */
export const L = (s) => (isAr() ? `⁦${s}⁩` : String(s ?? ''));

const half = () => (isAr() ? STRINGS.ar : STRINGS.en);

/** A value the demo data stores in English, read back in the chosen language. */
export function tr(branch, value) {
  const en = (STRINGS.en.data || {})[branch] || {};
  const cur = (half().data || {})[branch] || {};
  const keys = Object.keys(en);
  for (let i = 0; i < keys.length; i += 1) {
    if (en[keys[i]] === value) return cur[keys[i]] ?? value;
  }
  return value;
}

/** A category id (`bakes`) to its name in the chosen language. */
export const catName = (id) => (half().data.category[id] ?? id);

/** Timeline entries carry a sentence, and two of them carry a value in it. */
export function trTimeline(label) {
  const d = half().data;
  const raw = String(label || '');
  let m = /^Refunded (.+)$/.exec(raw);
  if (m) return d.timelineTpl.refunded({ amount: L(m[1]) });
  m = /^Moved to (\w+) by Cartline Assist$/.exec(raw);
  if (m) return d.timelineTpl.byAgent({ stage: d.statusRaw[m[1]] ?? m[1] });
  m = /^Set to (\w+)$/.exec(raw);
  if (m) return d.timelineTpl.setTo({ stage: d.statusRaw[m[1]] ?? m[1] });
  return tr('timeline', raw);
}

