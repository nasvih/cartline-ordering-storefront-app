/* ============================================================
   Cartline — the two languages, in one file.

   `en` is the source of truth: every string in it renders exactly what the
   app rendered before this file existed. `ar` is the same shape written for
   a Gulf reader — Modern Standard Arabic, not English with Arabic words in
   it. A key missing from `ar` falls back to `en` (see lib/i18n.js), so a gap
   shows up as English rather than as a key name.

   Three things live here besides the dictionaries, because they are language
   rather than layout:

   · arCount()   Arabic counts nouns in four shapes — طلب واحد / طلبان /
                 ٣ طلبات / ١٥ طلباً. Every counted noun in the Arabic half
                 goes through it.
   · L()         wraps a Latin run (an order number, a SKU, a product name)
                 in a left-to-right isolate so the punctuation around it does
                 not jump to the wrong end of the Arabic sentence. A no-op in
                 English.
   · tr()        translates a value that is *stored* in the demo data. The
                 store keeps its canonical English — an order placed in
                 English and read in Arabic has to work — so labels like
                 refund reasons and product descriptions are matched back to
                 their key at display time.
   ============================================================ */

